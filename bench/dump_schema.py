"""Regenerate bench/schema.sql from the pinned Sentry schema in the demo sink's template
database. Run via `make bench-schema` after `make schema`.

Emits the real DDL for the benched tables, stamped with the SENTRY_REF it came from so drift
against a newer pin is visible rather than silent. Foreign keys are dropped (their parent chains
would have to be seeded); an INDEXES marker splits table DDL from index DDL so the benches can
build an unindexed and an indexed sink from one file.
"""

import re
import subprocess
from pathlib import Path

TABLES = ["sentry_debugidartifactbundle", "sentry_groupedmessage"]
TEMPLATE = "sentry_template"
OUT = Path(__file__).with_name("schema.sql")

HEADER = """\
-- GENERATED by bench/dump_schema.py from the pinned Sentry schema -- do not hand-edit.
-- Regenerate with `make bench-schema` (needs `make schema` to have run first).
--
-- SENTRY_REF: {ref}
--
-- Foreign keys are stripped so the tables stand alone. Column types, CHECK constraints and every
-- index are unmodified: index count and row width are what the benches measure. Statements before
-- the INDEXES marker build the tables; those after add the indexes.
"""


def run(*args: str) -> str:
    return subprocess.run(args, capture_output=True, text=True, check=True).stdout


def sentry_ref() -> str:
    return run(
        "docker", "compose", "exec", "-T", "sink", "psql", "-U", "monarch", "-d", TEMPLATE, "-tAc",
        "SELECT shobj_description(oid, 'pg_database') FROM pg_database"
        f" WHERE datname = '{TEMPLATE}'",
    ).strip()


def dump() -> str:
    args = [a for t in TABLES for a in ("-t", t)]
    return run(
        "docker", "compose", "exec", "-T", "sink", "pg_dump", "-U", "monarch", "-d", TEMPLATE,
        "--schema-only", "--no-owner", "--no-acl", *args,
    )


def split(body: str) -> tuple[list[str], list[str]]:
    """Table statements and index statements, foreign keys discarded.

    Comments are stripped before splitting on `;`: pg_dump's headers carry semicolons of their own
    ("-- Name: x; Type: TABLE; ..."), so splitting first shreds them into fragments.
    """
    keep = [
        line
        for line in body.splitlines()
        if line.strip() and not line.lstrip().startswith(("--", "SET ", "SELECT pg_catalog", "\\"))
    ]
    tables, indexes = [], []
    for raw in "\n".join(keep).split(";"):
        statement = re.sub(r"\bpublic\.", "", raw).strip()
        if not statement or "FOREIGN KEY" in statement:
            continue
        (indexes if "INDEX" in statement or "UNIQUE" in statement else tables).append(statement)
    return tables, indexes


def main() -> None:
    tables, indexes = split(dump())
    body = ";\n\n".join(tables) + ";\n\n-- INDEXES\n\n" + ";\n".join(indexes) + ";\n"
    OUT.write_text(HEADER.format(ref=sentry_ref()) + "\n" + body)
    print(f"{OUT}: {len(tables)} tables, {len(indexes)} indexes")


if __name__ == "__main__":
    main()
